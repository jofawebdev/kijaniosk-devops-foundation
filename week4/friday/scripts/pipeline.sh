#!/usr/bin/env bash
set -Eeuo pipefail
IFS=$'\n\t'

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd -- "${SCRIPT_DIR}/../../.." && pwd)"
WEEK_DIR="${PROJECT_DIR}/week4/friday"
TF_DIR="${WEEK_DIR}/terraform"
ANSIBLE_DIR="${WEEK_DIR}/ansible"

log() {
  printf '[%s] %s\n' "$(date --iso-8601=seconds)" "$*"
}

fail() {
  log "ERROR: $*"
  exit 1
}

command -v terraform >/dev/null 2>&1 || fail "Terraform is not installed."
command -v ansible-playbook >/dev/null 2>&1 || fail "Ansible is not installed."
command -v python3 >/dev/null 2>&1 || fail "Python 3 is not installed."
[[ -r "${HOME}/.ssh/id_ed25519" ]] || fail "SSH private key ~/.ssh/id_ed25519 is missing."
[[ -r "${HOME}/.config/kijaniosk-week4/minio.env" ]] || \
  fail "Backend credentials file is missing; see environment-setup.md."

# Load local backend credentials without printing them or writing them to the repo.
set -a
# shellcheck disable=SC1091
source "${HOME}/.config/kijaniosk-week4/minio.env"
set +a
export AWS_ACCESS_KEY_ID="${MINIO_ROOT_USER:?MINIO_ROOT_USER is unset}"
export AWS_SECRET_ACCESS_KEY="${MINIO_ROOT_PASSWORD:?MINIO_ROOT_PASSWORD is unset}"
export AWS_EC2_METADATA_DISABLED=true

log "Initializing Terraform and remote backend."
terraform -chdir="${TF_DIR}" init -input=false

log "Validating Terraform configuration."
terraform -chdir="${TF_DIR}" validate

log "Applying the staging infrastructure."
terraform -chdir="${TF_DIR}" apply -input=false -auto-approve

log "Generating Ansible inventory from Terraform outputs."
python3 - "${TF_DIR}" "${ANSIBLE_DIR}/inventory.ini" "${HOME}/.ssh/id_ed25519" <<'PY'
import json
import subprocess
import sys
from pathlib import Path

tf_dir, inventory_path, private_key = sys.argv[1:]
raw = subprocess.check_output(
    ["terraform", "-chdir=" + tf_dir, "output", "-json"],
    text=True,
)
outputs = json.loads(raw)
ips = outputs["server_ips"]["value"]

expected = {"api", "payments", "logs"}
if set(ips) != expected:
    raise SystemExit(f"Expected server keys {sorted(expected)}, received {sorted(ips)}")

groups = {
    "api": ("kk-api", 3000, "0.0.0.0"),
    "payments": ("kk-payments", 3001, "127.0.0.1"),
    "logs": ("kk-logs", 3010, "0.0.0.0"),
}
lines = [
    "# Generated by scripts/pipeline.sh; do not edit by hand.",
    "[all:vars]",
    "ansible_user=ubuntu",
    f"ansible_ssh_private_key_file={private_key}",
    "ansible_python_interpreter=/usr/bin/python3",
    "",
]
for key, (host, port, bind) in groups.items():
    ip = ips[key]
    if not isinstance(ip, str) or not ip.strip():
        raise SystemExit(f"Terraform returned no IP for {key}")
    lines += [
        f"[{key}]",
        f"{host} ansible_host={ip}",
        "",
    ]

path = Path(inventory_path)
path.write_text("\n".join(lines) + "\n")
path.chmod(0o600)
print(f"Inventory written to {path}")
for key, (host, _, _) in groups.items():
    print(f"{host}: {ips[key]}")
PY

log "Configuring servers with Ansible."
ANSIBLE_CONFIG="${ANSIBLE_DIR}/ansible.cfg" \
  ansible-playbook \
    -i "${ANSIBLE_DIR}/inventory.ini" \
    "${ANSIBLE_DIR}/site.yml" \
    --diff

log "Pipeline completed successfully."
